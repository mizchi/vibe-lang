# Build lookup set for bundle reachability filter
is_bundle_reachable() {
  local target="$1"
  local idx
  for idx in "${BUNDLE_REACHABLE_INDEXES[@]}"; do
    if [ "$idx" = "$target" ]; then
      return 0
    fi
  done
  return 1
}

if [ "${#FILES[@]}" -eq 0 ]; then
  echo "error: manifest contains no compiler sources: $MANIFEST" >&2
  exit 1
fi

find_adapter_local_index() {
  local target="$1"
  local i=0
  local idx
  for idx in "${CLI_ADAPTER_INDEXES[@]}"; do
    if [ "$idx" = "$target" ]; then
      echo "$i"
      return 0
    fi
    i=$((i + 1))
  done
  return 1
}

find_bundle_local_index() {
  local target="$1"
  local pair manifest_idx local_idx
  for pair in "${BUNDLE_SOURCE_INDEXES[@]}"; do
    manifest_idx="${pair%%:*}"
    local_idx="${pair#*:}"
    if [ "$manifest_idx" = "$target" ]; then
      echo "$local_idx"
      return 0
    fi
  done
  return 1
}

is_main_ordered() {
  local target="$1"
  local idx
  for idx in "${MAIN_ORDERED_INDEXES[@]}"; do
    if [ "$idx" = "$target" ]; then
      return 0
    fi
  done
  return 1
}

