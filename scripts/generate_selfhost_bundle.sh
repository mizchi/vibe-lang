#!/usr/bin/env bash
# Generate selfhost_sources_bundle.vibe — all compiler source files as string constants.
# This allows the selfhost WASM to compile itself without filesystem access.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
COMPILER_DIR="$PROJECT_ROOT/vibe/compiler"
OUT="$COMPILER_DIR/selfhost_sources_bundle.vibe"

# Files reachable from index.vibe (in dependency order, dependencies first)
FILES=(
  polyfill.vibe
  ast.vibe
  token.vibe
  types.vibe
  bytebuf.vibe
  lexer.vibe
  parser.vibe
  printer.vibe
  builtins.vibe
  checker_resolve.vibe
  checker_pattern.vibe
  checker.vibe
  checker_stmt.vibe
  wasm_emit.vibe
  codegen_common.vibe
  codegen.vibe
  codegen_gc.vibe
  eval_loader.vibe
  module_loader.vibe
  compiler.vibe
  index.vibe
)

{
  echo "// AUTO-GENERATED by scripts/generate_selfhost_bundle.sh"
  echo "// Do not edit manually. Regenerate with: bash scripts/generate_selfhost_bundle.sh"
  echo ""
  echo "//# Selfhost source bundle"
  echo ""
  echo "// All compiler source files bundled as (path, source) pairs."
  echo "// Used by selfbuild_compile_stage2 to avoid filesystem access."
  echo "export let selfhost_sources = () -> Array[(String, String)] {"
  echo "  ["

  first=1
  for f in "${FILES[@]}"; do
    filepath="$COMPILER_DIR/$f"
    if [ ! -f "$filepath" ]; then
      echo "error: file not found: $filepath" >&2
      exit 1
    fi
    relpath="vibe/compiler/$f"
    if [ "$first" -eq 1 ]; then
      first=0
    else
      echo "    ,"
    fi
    echo "    (\"$relpath\","
    # Escape the source code for embedding in a vibe string literal
    # Need to escape: backslash -> \\, double quote -> \", newline -> \n
    python3 -c "
import sys
with open('$filepath', 'r') as f:
    content = f.read()
# Escape for vibe string literal
content = content.replace('\\\\', '\\\\\\\\')
content = content.replace('\"', '\\\\\"')
content = content.replace('\n', '\\\\n')
sys.stdout.write('\"' + content + '\"')
"
    echo ")"
  done

  echo "  ]"
  echo "}"
} > "$OUT"

echo "Generated $OUT ($(wc -l < "$OUT") lines, $(wc -c < "$OUT" | tr -d ' ') bytes)"
