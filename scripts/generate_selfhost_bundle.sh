#!/usr/bin/env bash
# Generate selfhost_sources_bundle.vibe — all compiler source files as string constants.
# This allows the selfhost WASM to compile itself without filesystem access.
set -euo pipefail
: "${VIBE_RC:=0}"; export VIBE_RC  # cutover: pin the compiler self-build / gate baseline to bump (RC only when explicitly VIBE_RC=1)

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
SCRIPT_PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
PROJECT_ROOT="${VIBE_SELFHOST_PROJECT_ROOT:-$(dirname "$SCRIPT_DIR")}"
COMPILER_DIR="${VIBE_SELFHOST_COMPILER_DIR:-$PROJECT_ROOT/vibe/compiler}"
MANIFEST="${VIBE_SELFHOST_SOURCE_MANIFEST:-$COMPILER_DIR/selfhost_sources_manifest.tsv}"
OUT="${VIBE_SELFHOST_BUNDLE_OUT:-$COMPILER_DIR/selfhost_sources_bundle.vibe}"
OUT_ADAPTER="${VIBE_SELFHOST_ADAPTER_BUNDLE_OUT:-$COMPILER_DIR/selfhost_cli_adapter_bundle.vibe}"
OUT_RUNTIME_ENTRY="${VIBE_SELFHOST_RUNTIME_ENTRY_BUNDLE_OUT:-$COMPILER_DIR/selfbuild_runtime_entry_bundle.vibe}"
ADAPTER_MODULE_SOURCE_OUT="${VIBE_SELFHOST_ADAPTER_MODULE_SOURCE_OUT:-}"

if [ ! -f "$MANIFEST" ]; then
  echo "error: manifest not found: $MANIFEST" >&2
  exit 1
fi

MANIFEST_GROUPS=()
FILES=()
while IFS=$'\t' read -r group relpath; do
  if [ -z "${group}${relpath}" ]; then
    continue
  fi
  case "$group" in
    \#*) continue ;;
  esac
  if [ -z "${relpath:-}" ]; then
    echo "error: invalid manifest row in $MANIFEST: missing path for group '$group'" >&2
    exit 1
  fi
  MANIFEST_GROUPS+=("$group")
  FILES+=("$relpath")
done < "$MANIFEST"

# #630: codegen fingerprint. Hash every compiler source file in the manifest
# (excluding generated bundles and the fingerprint file itself) and write it into
# cache/selfhost_codegen_fingerprint.vibe. persistent_cache folds this into the
# artifact cache key, so any change to codegen source invalidates stale compiled
# `.hex` artifacts even when the USER source is unchanged. Deterministic (manifest
# order); independent of its own output, so regeneration is stable.
CODEGEN_FP_FILE="$COMPILER_DIR/cache/selfhost_codegen_fingerprint.vibe"
# Portable sha256 over stdin (macOS install-smoke has no `sha256sum`, only
# `shasum`). Both print the hash first, so `cut -c1-16` yields the same 16 hex
# chars on either — the fingerprint value is unchanged.
sha256_stdin() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum
  else
    shasum -a 256
  fi
}
# Concatenate the codegen source files (excluding generated/self outputs). Kept a
# top-level function rather than inline in the `$(...)` below: bash 3.2 (macOS
# default) mis-parses a `case` nested in command substitution ("syntax error near
# unexpected token `newline'"), which broke the install-smoke generation step.
collect_codegen_sources() {
  local relpath f
  for relpath in "${FILES[@]}"; do
    case "$relpath" in
      *_bundle.vibe|*module_source*|cache/selfhost_codegen_fingerprint.vibe) continue ;;
    esac
    f="$COMPILER_DIR/$relpath"
    [ -f "$f" ] && cat "$f"
  done
}
codegen_fp="$(collect_codegen_sources | sha256_stdin | cut -c1-16)"
cat > "$CODEGEN_FP_FILE" <<FPEOF
// AUTO-GENERATED by scripts/generate_selfhost_bundle.sh (#630).
// Do not edit manually. Regenerate with: bash scripts/generate_selfhost_bundle.sh
//
// A hash of every compiler source file in selfhost_sources_manifest.tsv (the
// codegen included). persistent_cache folds it into the artifact cache key so a
// codegen change — which produces different wasm from the SAME user source —
// automatically invalidates stale compiled .hex artifacts (#630).

//# Functions

export let selfhost_codegen_fingerprint: () -> String = () -> {
  "$codegen_fp"
}
FPEOF

cli_adapter_index_rows_file="$(mktemp)"
# Reachability analysis: adapter entry + GC backend as additional entry
# Outputs:
#   reachable\t<idx>        — files reachable from adapter entry
#   ordered\t<idx>          — dependency-ordered files from adapter entry
#   bundle_reachable\t<idx> — files reachable from adapter entry + GC backend (for main bundle)
python3 - "$COMPILER_DIR" "$MANIFEST" "selfhost_cli_adapter.vibe" >"$cli_adapter_index_rows_file" <<'PY'
import os
import re
import sys

compiler_dir, manifest_path, root_rel = sys.argv[1:]
rows = []
for raw in open(manifest_path, "r", encoding="utf-8"):
    line = raw.rstrip("\n")
    if not line or line.startswith("#"):
        continue
    parts = line.split("\t")
    if len(parts) != 2:
        continue
    rows.append((parts[0], parts[1]))

source_by_rel = {}
for _, rel in rows:
    full = os.path.join(compiler_dir, rel)
    if os.path.isfile(full):
        with open(full, "r", encoding="utf-8") as f:
            source_by_rel[rel] = f.read()

dep_pattern = re.compile(r'^\s*(?:import|export)\s+(\.[\w./\s-]+?)(?:\.vibe)?\s*\{', re.MULTILINE)

def normalize_path(path: str) -> str:
    parts = []
    for seg in path.split("/"):
        if seg == "" or seg == ".":
            continue
        if seg == "..":
            if parts:
                parts.pop()
            continue
        parts.append(seg)
    return "/".join(parts)

def resolve_path(base_rel: str, raw_path: str) -> str:
    base_dir = os.path.dirname(base_rel)
    raw_path = re.sub(r'\s*/\s*', '/', raw_path.strip())
    path = raw_path if raw_path.endswith(".vibe") else raw_path + ".vibe"
    if path.startswith("./") or path.startswith("../"):
        if base_dir:
            candidate = normalize_path(base_dir + "/" + path)
        else:
            candidate = normalize_path(path)
    else:
        candidate = normalize_path(path)
    if candidate in source_by_rel:
        return candidate
    # Try index.vibe fallback for directory-style imports
    idx_candidate = candidate.replace(".vibe", "/index.vibe")
    if idx_candidate in source_by_rel:
        return idx_candidate
    return candidate

reachable = set()

def visit(rel: str):
    if rel in reachable:
        return
    source = source_by_rel.get(rel)
    if source is None:
        return
    reachable.add(rel)
    for dep in dep_pattern.findall(source):
        visit(resolve_path(rel, dep))

visit(root_rel)
index_by_rel = {}
for pair_index, (_, rel) in enumerate(rows):
    index_by_rel[rel] = pair_index
for idx, (_, rel) in enumerate(rows):
    if rel in reachable:
        print("reachable\t" + str(idx))

visited = set()
ordered = []

def visit_ordered(rel: str):
    if rel in visited:
        return
    source = source_by_rel.get(rel)
    if source is None:
        return
    visited.add(rel)
    for dep in dep_pattern.findall(source):
        visit_ordered(resolve_path(rel, dep))
    ordered.append(rel)

visit_ordered(root_rel)
for rel in ordered:
    idx = index_by_rel.get(rel)
    if idx is not None:
        print("ordered\t" + str(idx))

# Bundle reachability: adapter entry + GC backend
bundle_reachable = set(reachable)

def visit_bundle(rel: str):
    if rel in bundle_reachable:
        return
    source = source_by_rel.get(rel)
    if source is None:
        return
    bundle_reachable.add(rel)
    for dep in dep_pattern.findall(source):
        visit_bundle(resolve_path(rel, dep))

# Additional entry points for the main bundle
bundle_extra_entries = os.environ.get("VIBE_SELFHOST_BUNDLE_EXTRA_ENTRIES", "codegen/gc/index.vibe,index.vibe")
for entry in bundle_extra_entries.split(","):
    entry = entry.strip()
    if entry:
        visit_bundle(entry)

for idx, (_, rel) in enumerate(rows):
    if rel in bundle_reachable:
        print("bundle_reachable\t" + str(idx))
PY
CLI_ADAPTER_INDEXES=()
CLI_ADAPTER_ORDERED_INDEXES=()
BUNDLE_REACHABLE_INDEXES=()
while IFS=$'\t' read -r kind idx; do
  if [ -z "${kind}${idx}" ]; then
    continue
  fi
  if [ "$kind" = "reachable" ]; then
    CLI_ADAPTER_INDEXES+=("$idx")
  elif [ "$kind" = "ordered" ]; then
    CLI_ADAPTER_ORDERED_INDEXES+=("$idx")
  elif [ "$kind" = "bundle_reachable" ]; then
    BUNDLE_REACHABLE_INDEXES+=("$idx")
  fi
done < "$cli_adapter_index_rows_file"
rm -f "$cli_adapter_index_rows_file"

