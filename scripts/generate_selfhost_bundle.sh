    content = f.read()
content = content.replace("\\", "\\\\")
content = content.replace('"', '\\"')
content = content.replace("\n", "\\n")
sys.stdout.write('"' + content + '"')
PY
}

write_vibe_chunked_string_function_from_file() {
  local prefix="$1"
  local export_name="$2"
  local filepath="${3:-}"
  local chunk_size="${VIBE_SELFHOST_BUNDLE_CHUNK_SIZE:-8192}"
  if [ -z "$filepath" ] || [ ! -f "$filepath" ]; then
    echo "export let $export_name = () -> String {"
    echo "  \"\""
    echo "}"
    return 0
  fi
  python3 - "$filepath" "$prefix" "$export_name" "$chunk_size" <<'PY'
import sys

filepath, prefix, export_name, chunk_size = sys.argv[1:]
chunk_size = int(chunk_size)
with open(filepath, "r", encoding="utf-8") as f:
    content = f.read()

def esc(text: str) -> str:
    text = text.replace("\\", "\\\\")
    text = text.replace('"', '\\"')
    text = text.replace("\n", "\\n")
    return text

chunks = [content[i:i + chunk_size] for i in range(0, len(content), chunk_size)]
if not chunks:
    chunks = [""]

print(f"export let {export_name} = () -> String {{")
if len(chunks) == 1:
    print(f'  "{esc(chunks[0])}"')
else:
    print("  let sb = StringBuilder::new()")
    for chunk in chunks:
        print(f'  StringBuilder::push(sb, "{esc(chunk)}")')
    print("  StringBuilder::freeze(sb)")
print("}")
PY
}

write_vibe_string_function_from_file() {
  local binding_name="$1"
  local export_name="$2"
  local filepath="${3:-}"
  if [ -z "$filepath" ] || [ ! -f "$filepath" ]; then
    echo "export let $export_name = () -> String {"
    echo "  \"\""
    echo "}"
    return 0
  fi
  echo "export let $export_name = () -> String {"
  printf '  '
  write_vibe_string_literal_from_file "$filepath"
  echo ""
  echo "}"
}

run_host_vibe_cmd() {
  local cmd="$1"
  shift
  local release_vibe="$SCRIPT_PROJECT_ROOT/_build/native/release/build/cmd/vibe/vibe.exe"
  local debug_vibe="$SCRIPT_PROJECT_ROOT/_build/native/debug/build/cmd/vibe/vibe.exe"
  if [ "$cmd" = "emit-module-source" ]; then
    # #594 Stage 1b/seed-bump: prefer the selfhost seed compiler (moon-free).
    # The seed carries emit-module-source (VIBE_EMIT_MODULE_SOURCE mode), so the
    # flat module source needs no MoonBit host. Args are (input, output, entry),
    # rewritten to repo-root-relative for the wasm preopen. Force the legacy host
    # path with VIBE_SELFHOST_EMIT_VIA_HOST=1.
    local seed_wasm="$SCRIPT_PROJECT_ROOT/bootstrap/selfhost/seed/selfhost_compiler.wasm"
    if [ -f "$seed_wasm" ] && [ "${VIBE_SELFHOST_EMIT_VIA_HOST:-0}" != "1" ]; then
      local emit_in="${1#"$SCRIPT_PROJECT_ROOT"/}"
      local emit_out="${2#"$SCRIPT_PROJECT_ROOT"/}"
      local emit_entry="${3:-cli_main}"
      (
        cd "$SCRIPT_PROJECT_ROOT" &&
          VIBE_PREOPEN_DIR="$SCRIPT_PROJECT_ROOT" \
            VIBE_EMIT_MODULE_SOURCE=1 \
            VIBE_SELFHOST_IMPORT_ABI="${VIBE_SELFHOST_IMPORT_ABI:-raw}" \
            bash "$SCRIPT_PROJECT_ROOT/scripts/run_wasm_vibe_host_runner.sh" \
            --invoke cli_main "$seed_wasm" "$emit_in" "$emit_out" "$emit_entry"
      )
      return 0
    fi
    if [ -x "$release_vibe" ]; then
      (cd "$SCRIPT_PROJECT_ROOT" && "$release_vibe" "$cmd" "$@")
      return 0
    fi
    if [ -x "$debug_vibe" ]; then
      (cd "$SCRIPT_PROJECT_ROOT" && "$debug_vibe" "$cmd" "$@")
      return 0
    fi
    (cd "$SCRIPT_PROJECT_ROOT" && moon build --target native --release src/cmd/vibe --warn-list '-1-7-24-29' >/dev/null)
    "$release_vibe" "$cmd" "$@"
    return 0
  fi
  if [ -x "$release_vibe" ]; then
    (cd "$SCRIPT_PROJECT_ROOT" && "$release_vibe" "$cmd" "$@")
    return 0
  fi
  if [ -x "$debug_vibe" ]; then
    (cd "$SCRIPT_PROJECT_ROOT" && "$debug_vibe" "$cmd" "$@")
    return 0
  fi
  (cd "$SCRIPT_PROJECT_ROOT" && moon run --target native src/cmd/vibe -- "$cmd" "$@")
}

build_adapter_module_source() {
  local merged_source_file="$1"
  # Fast path for tiny shell self-tests; production generation uses
  # emit-module-source through the host compiler below.
  if [ "${VIBE_SELFHOST_ADAPTER_MODULE_SOURCE_FROM_MERGED:-0}" = "1" ]; then
    local module_source_path
    mkdir -p "$PROJECT_ROOT/_build"
    module_source_path="$(mktemp "$PROJECT_ROOT/_build/selfhost_cli_adapter_module_source.XXXXXX")"
    python3 - "$merged_source_file" "$module_source_path" <<'PY'
import sys

src, out = sys.argv[1:]
with open(src, "r", encoding="utf-8") as f:
    lines = f.readlines()

with open(out, "w", encoding="utf-8") as f:
    for line in lines:
        stripped = line.lstrip()
        if stripped.startswith("let ") and "->" not in stripped:
            continue
        f.write(line)
PY
    printf '%s\n' "$module_source_path"
    return 0
  fi
  # Moon-free default (#594 Stage 1): prefer the committed prebuilt flat
  # module source so that seed -> stage1 -> stage2 needs no MoonBit host.
  # emit-module-source is a deterministic function of the compiler source;
  # the committed copy is kept fresh by scripts/check_selfhost_module_source_sync.sh
  # (run in selfhost-gate). Force regeneration through the host compiler with
  # VIBE_SELFHOST_REGEN_MODULE_SOURCE=1 (used by that gate and by intentional
  # module-source bumps).
  local committed_module_source="$COMPILER_DIR/selfhost_cli_adapter_module_source.vibe"
  if [ "${VIBE_SELFHOST_REGEN_MODULE_SOURCE:-0}" != "1" ] && [ -s "$committed_module_source" ]; then
    local module_source_path
    mkdir -p "$PROJECT_ROOT/_build"
    module_source_path="$(mktemp "$PROJECT_ROOT/_build/selfhost_cli_adapter_module_source.XXXXXX")"
    cp "$committed_module_source" "$module_source_path"
    printf '%s\n' "$module_source_path"
    return 0
  fi
  local module_source_path
  mkdir -p "$PROJECT_ROOT/_build"
  module_source_path="$(mktemp "$PROJECT_ROOT/_build/selfhost_cli_adapter_module_source.XXXXXX")"
  run_host_vibe_cmd emit-module-source "$merged_source_file" "$module_source_path" "cli_main" >/dev/null
  printf '%s\n' "$module_source_path"
}

write_adapter_bundle() {
  local merged_source_file="${1:-}"
  local module_source_file="${2:-}"
  {
  echo "// AUTO-GENERATED by scripts/generate_selfhost_bundle.sh"
  echo "// Do not edit manually. Regenerate with: bash scripts/generate_selfhost_bundle.sh"
  echo ""
  echo "//# Selfhost CLI adapter bundle"
  echo ""
  echo "let cli_adapter_empty_grouped_sources = () -> Array[(String, Array[(String, String)])] {"
  echo "  Array::slice([(\"\", Array::slice([(\"\", \"\")], 0, 0))], 0, 0)"
  echo "}"
  echo ""
  echo "let cli_adapter_push_grouped_source_pair = (groups: Array[(String, Array[(String, String)])], group_name: String, pair: (String, String)) -> Unit {"
  echo "  let (path, source) = pair"
  echo "  let mut i = 0"
  echo "  let mut found = false"
  echo "  while i < Array::length(groups) {"
  echo "    let (name, sources) = Array::get(groups, i)"
  echo "    if String::equals(name, group_name) {"
  echo "      Array::push(sources, (path, source))"
  echo "      found = true"
  echo "      i = Array::length(groups)"
  echo "    } else {"
  echo "      i = i + 1"
  echo "    }"
  echo "  }"
  echo "  if !found {"
  echo "    let sources = Array::slice([(\"\", \"\")], 0, 0)"
  echo "    Array::push(sources, (path, source))"
  echo "    Array::push(groups, (group_name, sources))"
  echo "  }"
  echo "}"
  echo ""

  adapter_local_idx=0
  for idx in "${CLI_ADAPTER_INDEXES[@]}"; do
    f="${FILES[$idx]}"
    filepath="$COMPILER_DIR/$f"
    relpath="vibe/compiler/$f"
    echo "let cli_adapter_source_$adapter_local_idx = () -> (String, String) {"
    echo "  (\"$relpath\","
    write_vibe_string_literal_from_file "$filepath"
    echo ")"
    echo "}"
    echo ""
    adapter_local_idx=$((adapter_local_idx + 1))
  done

  echo "export let selfhost_cli_adapter_sources = () -> Array[(String, String)] {"
  echo "  let sources = Array::slice([(\"\", \"\")], 0, 0)"
  adapter_local_idx=0
  for _idx in "${CLI_ADAPTER_INDEXES[@]}"; do
    echo "  Array::push(sources, cli_adapter_source_$adapter_local_idx())"
    adapter_local_idx=$((adapter_local_idx + 1))
  done
  echo "  sources"
  echo "}"
  echo ""
  echo "export let selfhost_cli_adapter_source_groups = () -> Array[(String, Array[(String, String)])] {"
  echo "  let groups = cli_adapter_empty_grouped_sources()"
  adapter_local_idx=0
  for idx in "${CLI_ADAPTER_INDEXES[@]}"; do
    group="${MANIFEST_GROUPS[$idx]}"
    echo "  cli_adapter_push_grouped_source_pair(groups, \"$group\", cli_adapter_source_$adapter_local_idx())"
    adapter_local_idx=$((adapter_local_idx + 1))
  done
  echo "  groups"
  echo "}"
  echo ""
  echo "export let selfhost_cli_adapter_ordered_sources = () -> Array[(String, String)] {"
  echo "  let sources = Array::slice([(\"\", \"\")], 0, 0)"
  for idx in "${CLI_ADAPTER_ORDERED_INDEXES[@]}"; do
    adapter_local_idx="$(find_adapter_local_index "$idx")"
    echo "  Array::push(sources, cli_adapter_source_$adapter_local_idx())"
  done
  echo "  sources"
  echo "}"
  echo ""
  write_vibe_string_function_from_file \
    "selfhost_cli_adapter_merged_source_value" \
    "selfhost_cli_adapter_merged_source" \
    "$merged_source_file"
  echo ""
  write_vibe_string_function_from_file \
    "selfhost_cli_adapter_module_source_value" \
    "selfhost_cli_adapter_module_source" \
    "$module_source_file"
  } > "$OUT_ADAPTER"
}

