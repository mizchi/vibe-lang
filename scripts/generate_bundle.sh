# Build lookup set for bundle reachability filter
is_bundle_reachable() {
  local target="$1"
  local idx
  for idx in "${BUNDLE_REACHABLE_INDEXES[@]}"; do
    if [ "$idx" = "$target" ]; then
      return 0
    fi
  done
  return 1
}

if [ "${#FILES[@]}" -eq 0 ]; then
  echo "error: manifest contains no compiler sources: $MANIFEST" >&2
