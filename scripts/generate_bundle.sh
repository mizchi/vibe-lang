#!/usr/bin/env bash
# Generate compiler_sources_bundle.vibe — all compiler source files as string constants.
# This allows the compiler wasm to compile itself without filesystem access.
set -euo pipefail
: "${VIBE_RC:=0}"; export VIBE_RC  # cutover: pin the compiler self-build / gate baseline to bump (RC only when explicitly VIBE_RC=1)

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
SCRIPT_PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
PROJECT_ROOT="${VIBE_PROJECT_ROOT:-$(dirname "$SCRIPT_DIR")}"
. "$PROJECT_ROOT/scripts/trace_lib.sh"
COMPILER_DIR="${VIBE_COMPILER_DIR:-$PROJECT_ROOT/lib/@vibe/compiler}"
MANIFEST="${VIBE_SOURCE_MANIFEST:-$COMPILER_DIR/compiler_sources_manifest.tsv}"
OUT="${VIBE_BUNDLE_OUT:-$COMPILER_DIR/compiler_sources_bundle.vibe}"
OUT_ADAPTER="${VIBE_ADAPTER_BUNDLE_OUT:-$COMPILER_DIR/cli_adapter_bundle.vibe}"
OUT_RUNTIME_ENTRY="${VIBE_RUNTIME_ENTRY_BUNDLE_OUT:-$COMPILER_DIR/selfbuild_runtime_entry_bundle.vibe}"
ADAPTER_MODULE_SOURCE_OUT="${VIBE_ADAPTER_MODULE_SOURCE_OUT:-}"

if [ ! -f "$MANIFEST" ]; then
  echo "error: manifest not found: $MANIFEST" >&2
  exit 1
fi

MANIFEST_GROUPS=()
FILES=()
while IFS=$'\t' read -r group relpath; do
  if [ -z "${group}${relpath}" ]; then
    continue
  fi
  case "$group" in
    \#*) continue ;;
  esac
  if [ -z "${relpath:-}" ]; then
    echo "error: invalid manifest row in $MANIFEST: missing path for group '$group'" >&2
    exit 1
  fi
  MANIFEST_GROUPS+=("$group")
  FILES+=("$relpath")
done < "$MANIFEST"

# #630: codegen fingerprint. Hash every compiler source file in the manifest
# (excluding generated bundles and the fingerprint file itself) and write it into
# cache/codegen_fingerprint.vibe. persistent_cache folds this into the
# artifact cache key, so any change to codegen source invalidates stale compiled
# `.hex` artifacts even when the USER source is unchanged. Deterministic (manifest
# order); independent of its own output, so regeneration is stable.
CODEGEN_FP_FILE="$COMPILER_DIR/cache/codegen_fingerprint.vibe"
# Portable sha256 over stdin (macOS install-smoke has no `sha256sum`, only
# `shasum`). Both print the hash first, so `cut -c1-16` yields the same 16 hex
# chars on either — the fingerprint value is unchanged.
sha256_stdin() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum
  else
    shasum -a 256
  fi
}
# Concatenate the codegen source files (excluding generated/self outputs). Kept a
# top-level function rather than inline in the `$(...)` below: bash 3.2 (macOS
# default) mis-parses a `case` nested in command substitution ("syntax error near
# unexpected token `newline'"), which broke the install-smoke generation step.
collect_codegen_sources() {
  local relpath f
  for relpath in "${FILES[@]}"; do
    case "$relpath" in
      *_bundle.vibe|*module_source*|cache/codegen_fingerprint.vibe) continue ;;
    esac
    f="$COMPILER_DIR/$relpath"
    [ -f "$f" ] && cat "$f"
  done
}
codegen_fp="$(collect_codegen_sources | sha256_stdin | cut -c1-16)"
cat > "$CODEGEN_FP_FILE" <<FPEOF
// AUTO-GENERATED by scripts/generate_bundle.sh (#630).
// Do not edit manually. Regenerate with: bash scripts/generate_bundle.sh
//
// A hash of every compiler source file in compiler_sources_manifest.tsv (the
// codegen included). persistent_cache folds it into the artifact cache key so a
// codegen change — which produces different wasm from the SAME user source —
// automatically invalidates stale compiled .hex artifacts (#630).

//# Functions

export let codegen_fingerprint: () -> String = () -> {
  "$codegen_fp"
}
FPEOF

