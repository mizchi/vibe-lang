run_host_vibe_cmd() {
  local cmd="$1"
  shift
  if [ "$cmd" = "emit-module-source" ]; then
    # #594 Stage 1b/seed-bump: the selfhost seed compiler carries
    # emit-module-source (VIBE_EMIT_MODULE_SOURCE mode), so the flat module
    # source needs no MoonBit host. Args are (input, output, entry), rewritten
    # to repo-root-relative for the wasm preopen. The former fallbacks —
    # `_build/native/**/vibe.exe` and `moon build/run src/cmd/vibe`, selected by
    # VIBE_EMIT_VIA_HOST=1 — were retired with the MoonBit host: nothing in this
    # repo can build that binary any more, so the seed is the only path.
    local seed_wasm="$SCRIPT_PROJECT_ROOT/bootstrap/seed/compiler.wasm"
    if [ -f "$seed_wasm" ]; then
      local emit_in="${1#"$SCRIPT_PROJECT_ROOT"/}"
      local emit_out="${2#"$SCRIPT_PROJECT_ROOT"/}"
      local emit_entry="${3:-cli_main}"
      (
        cd "$SCRIPT_PROJECT_ROOT" &&
          VIBE_PREOPEN_DIR="$SCRIPT_PROJECT_ROOT" \
            VIBE_EMIT_MODULE_SOURCE=1 \
            VIBE_IMPORT_ABI="${VIBE_IMPORT_ABI:-raw}" \
            bash "$SCRIPT_PROJECT_ROOT/scripts/run_wasm_vibe_host_runner.sh" \
            --invoke cli_main "$seed_wasm" "$emit_in" "$emit_out" "$emit_entry"
      )
      return 0
    fi
    echo "generate_bundle: emit-module-source needs the seed compiler at $seed_wasm (run scripts/ensure_seed.sh)" >&2
    return 1
  fi
  echo "generate_bundle: no host compiler for '$cmd' — the MoonBit host was retired (#594); only emit-module-source is served, via the seed" >&2
  return 1
}

build_adapter_module_source() {
  local merged_source_file="$1"
  # Fast path for tiny shell self-tests; production generation uses
  # emit-module-source through the host compiler below.
  if [ "${VIBE_ADAPTER_MODULE_SOURCE_FROM_MERGED:-0}" = "1" ]; then
    local module_source_path
    mkdir -p "$PROJECT_ROOT/_build"
    module_source_path="$(mktemp "$PROJECT_ROOT/_build/cli_adapter_module_source.XXXXXX")"
    python3 - "$merged_source_file" "$module_source_path" <<'PY'
import sys

src, out = sys.argv[1:]
with open(src, "r", encoding="utf-8") as f:
    lines = f.readlines()

with open(out, "w", encoding="utf-8") as f:
    for line in lines:
        stripped = line.lstrip()
        if stripped.startswith("let ") and "->" not in stripped:
            continue
        f.write(line)
PY
    printf '%s\n' "$module_source_path"
    return 0
  fi
  # The flat module source is a deterministic function of the compiler source,
  # so it is ALWAYS regenerated here. It used to be read back from the committed
  # _cli_adapter_module_source.vibe unless VIBE_REGEN_MODULE_SOURCE=1 was set --
  # a silent staleness trap: a source edit that nobody thought to regenerate for
  # produced a compiler WITHOUT that edit, and the build reported success. (Cost
  # of that trap, measured: three full rebuilds spent measuring a compiler that
  # did not contain the change under test.) Freshness is now decided ONCE, by
  # fingerprint, in scripts/ensure_generated.sh -- reaching this function at all
  # means the answer was already "regenerate".
  local module_source_path
  mkdir -p "$PROJECT_ROOT/_build"
  module_source_path="$(mktemp "$PROJECT_ROOT/_build/cli_adapter_module_source.XXXXXX")"
  # #1137: DCE-root at "main" (cli_adapter.vibe), not "cli_main" -- `main`'s
  # own body calls `cli_main()` directly, so the existing (unmodified,
  # seed-compatible) reachability walk in core/dce.vibe follows that
  # reference and keeps `cli_main` alive too (a strict superset of what
  # "cli_main" alone would keep). Rooting at "cli_main" instead would DCE
  # `main` away entirely, since cli_main never references it back. This
  # relies on no new emit-module-source behavior, so it works against the
  # currently-pinned seed with no bootstrap bump.
  run_host_vibe_cmd emit-module-source "$merged_source_file" "$module_source_path" "main" >/dev/null
  printf '%s\n' "$module_source_path"
}

