manifest_gaps = {}

def record_gap(user: str, target: str):
    probes = [target]
    if target.endswith(".vibe"):
        stem = target[: -len(".vibe")]
        probes += [stem + "/index.vpkg", stem + "/index.vibei", stem + "/index.vibe"]
    for probe in probes:
        if os.path.isfile(os.path.join(compiler_dir, probe)):
            manifest_gaps.setdefault(probe, []).append(user)
            return

def visit(rel: str):
    if rel in reachable:
        return
    source = source_by_rel.get(rel)
    if source is None:
        return
    reachable.add(rel)
    found = 0
    for dep in dep_pattern.findall(source):
        found += 1
        target = resolve_path(rel, dep)
        if target not in source_by_rel:
            record_gap(rel, target)
        visit(target)
    if wants_contract_discovery(rel, found):
        for sib in contract_sibling_rels(rel):
            if sib not in source_by_rel:
                record_gap(rel, sib)
            visit(sib)

